function filterRussianJobs(query) {
  let jobs = RUSSIAN_JOBS;

  if (query && query.trim() !== '') {
    const q = query.trim().toLowerCase();
    jobs = jobs.filter((job) => {
      const text = `${job.title} ${job.company} ${job.location} ${job.salary} ${job.description}`.toLowerCase();
      return text.includes(q);
    });
  }

  return jobs.sort((a, b) => new Date(b.created_at) - new Date(a.created_at));
}

function mapRussianJob(job) {
  return {
    id: job.id,
    title: job.title,
    company: job.company,
    location: job.location,
    salary: job.salary,
    description: job.description,
    created_at: job.created_at,
    source: 'russian',
    url: '',
  };
}

module.exports = { RUSSIAN_JOBS, filterRussianJobs, mapRussianJob };
